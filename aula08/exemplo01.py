# listas
# permite gravar mais de um elemento dentro dela
# coleção mutável (inserir, apagar, modificar)
# permite acesso por indíces
#                     0        1        2          3        4
lista_produtos = ['Celular', 'TV', 'Monitor', 'Cadeira', 'Mesa']
print(lista_produtos)
print(lista_produtos[1])
print(lista_produtos[0])
print(lista_produtos[-1]) # pegar do ultimo
print(lista_produtos[1:4]) # fatiar